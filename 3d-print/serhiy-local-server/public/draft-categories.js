export const draftCategories = Object.freeze(definitions.map(([label, broadType]) => Object.freeze({ label, broadType })));
export const nomenclatureTypes = Object.freeze(["Брелок", "Фігурка", "Функціональний аксесуар", "Інше"]);

export function nomenclatureTypeForDraftCategory(value) {
  const category = draftCategories.find((item) => item.label === String(value || "").trim());
  if (!category) throw new Error("Оберіть механіку / категорію зі списку.");
  return category.broadType;
}
