import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
const root=process.cwd(), base=path.join(root,'work/pay002-order-amount');
const source=path.join(root,'work/pay002-final-audit/source');
const php=process.env.PAY002_TEST_PHP || 'C:/laragon/bin/php/php-8.3.30-Win32-vs16-x64/php.exe';
const name='PAY-002_pumb-order-amount_20260831.php';
const runner=fs.readFileSync(path.join(root,'patches',name),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(base,'manifest.json')));
const [file]=Object.keys(manifest.files);
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
const check=(ok,label)=>{if(!ok)throw Error(label);};
function fixture(label){
 const dir=fs.mkdtempSync(path.join(base,label+'-'));
 fs.mkdirSync(path.dirname(path.join(dir,file)),{recursive:true});
 fs.copyFileSync(path.join(source,file),path.join(dir,file));
 fs.writeFileSync(path.join(dir,'config.php'),'<?php // isolated test only\n');
 fs.writeFileSync(path.join(dir,name),runner);return dir;
}
function run(dir){const r=spawnSync(php,[name],{cwd:dir,encoding:'utf8'});if(r.error)throw r.error;return r;}
const clean=fixture('runner-clean');let r=run(clean);
check(r.status===0,r.stdout+r.stderr);
check(hash(fs.readFileSync(path.join(clean,file)))===manifest.files[file].after,'after SHA');
check(!fs.existsSync(path.join(clean,name)),'self-delete');
const backups=fs.readdirSync(path.join(clean,'_patch_backups'));
check(backups.length===1,'one backup');
check(hash(fs.readFileSync(path.join(clean,'_patch_backups',backups[0],file)))===manifest.files[file].before,'backup SHA');
fs.writeFileSync(path.join(clean,name),runner);r=run(clean);
check(r.status===0&&r.stdout.includes('already_applied=yes')&&!fs.existsSync(path.join(clean,name)),'idempotence');
console.log('PASS exact source -> after SHA; backup SHA; self-delete; repeat');
const drift=fixture('runner-drift');fs.appendFileSync(path.join(drift,file),'\n// unrelated owner edit\n');
const driftHash=hash(fs.readFileSync(path.join(drift,file)));r=run(drift);
check(r.status!==0&&r.stderr.includes('write skipped'),'drift refusal');
check(hash(fs.readFileSync(path.join(drift,file)))===driftHash&&!fs.existsSync(path.join(drift,'_patch_backups')),'drift preserved');
console.log('PASS source drift refused without write');
const rollback=fixture('runner-rollback');
const encoded=runner.match(/base64_decode\('([^']+)'/)[1];const fault=JSON.parse(Buffer.from(encoded,'base64').toString());
fault.files[file].edits.push({label:'fixture lint fault',before:'<?php',after:'<?php !!! invalid syntax'});
let content=fs.readFileSync(path.join(source,file),'utf8');for(const e of fault.files[file].edits)content=content.replace(e.before,e.after);
fault.files[file].after=hash(content);
fs.writeFileSync(path.join(rollback,name),runner.replace(encoded,Buffer.from(JSON.stringify(fault)).toString('base64')));
r=run(rollback);
check(r.status!==0&&r.stderr.includes('source restored: PHP lint failed'),'rollback executed');
check(hash(fs.readFileSync(path.join(rollback,file)))===manifest.files[file].before,'rollback exact source');
console.log('PASS injected lint fault restores exact original');
const test=path.join(root,'scripts/tests/pay002-order-amount.test.php');
r=spawnSync(php,['-n',test,path.join(source,file)],{encoding:'utf8'});if(r.error)throw r.error;
check(r.status!==0&&(r.stdout+r.stderr).includes('canonical_amount'),'baseline fails amount test');
r=spawnSync(php,['-n',test,path.join(clean,file)],{encoding:'utf8'});if(r.error)throw r.error;
check(r.status===0,r.stdout+r.stderr);console.log(r.stdout.trim());
console.log('PASS tests against ACTUAL runner-generated controller');
